import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
const base = process.env.S1_TEST_URL ?? 'http://127.0.0.1:3331';
const prefix = `${base}/api/mock/v1`;
const folder = process.env.S1_TEST_FOLDER ?? 'qa-s1-api';
assert.match(folder, /^qa-s1[a-z0-9-]*$/);
const stateFile = path.resolve('.soky-demo', folder, 'state.json');
let cookie = '';
let checks = 0;
const pass = name => { checks++; console.log(`PASS ${name}`); };
async function request(resource, { method = 'GET', body, session = true, origin = base } = {}) {
  const response = await fetch(prefix + resource, { method, headers: { ...(session && cookie ? {Cookie:cookie} : {}), ...(method !== 'GET' ? { Origin:origin, 'Content-Type':'application/json' } : {}) }, body:body === undefined ? undefined : JSON.stringify(body) });
  const data = await response.json();
  return { response, data };
}
for (const route of ['/admin/products','/admin/categories','/admin/settings','/admin/sliders','/admin/exchange-rates/current','/admin/demo/status','/admin/demo/workspace']) assert.equal((await request(route, {session:false})).response.status, 401);
const direct = await fetch(`${base}/admin-secret/products`, {redirect:'manual'});
const directHtml = await direct.text();
assert.ok(direct.status === 307 || (direct.status === 200 && directHtml.includes('NEXT_REDIRECT') && directHtml.includes('http-equiv="refresh"')));
assert.ok((direct.headers.get('location') ?? directHtml).includes('/admin-secret/login'));
pass('Direct protected page redirects; admin endpoints reject missing cookie');
assert.equal((await request('/auth/login', {method:'POST',body:{email:'admin@soky.test',password:'wrong'},session:false})).response.status,401);
assert.equal((await request('/auth/login', {method:'POST',body:{email:'admin@soky.test',password:'demo'},session:false,origin:'https://evil.test'})).response.status,403);
const login = await request('/auth/login', {method:'POST',body:{email:'admin@soky.test',password:'demo'},session:false});
assert.equal(login.response.status,200);
const setCookie = login.response.headers.get('set-cookie');
assert.match(setCookie,/HttpOnly/i); assert.match(setCookie,/SameSite=lax/i); assert.match(setCookie,/Path=\//i);
cookie = setCookie.split(';')[0];
assert.equal((await request('/auth/me')).response.status,200);
assert.equal((await request('/auth/refresh',{method:'POST'})).response.status,200);
pass('Valid/invalid login, same-origin protection, HttpOnly cookie, me and refresh');
const startingStatus = (await request('/admin/demo/status')).data;
assert.equal((await request('/admin/demo/reset',{method:'POST',body:{expectedRevision:startingStatus.storageState === 'corrupt' ? 'RECOVER' : startingStatus.revision,confirm:'RESTORE'}})).response.status,200);
const workspace = await request('/admin/demo/workspace');
assert.equal(workspace.response.status,200);
const seed = workspace.data;
const product = seed.products.find(p=>p.status==='ACTIVE');
const publicProduct = await request(`/products/${product.slug}`,{session:false});
assert.deepEqual(publicProduct.data,product);
assert.equal(publicProduct.response.headers.get('x-demo-revision'),String(seed.revision));
pass('Admin and public routes share product and revision across compiled bundles');
const edits = await Promise.all(['A','B'].map(title=>request(`/admin/products/${product.id}`,{method:'PATCH',body:{expectedRevision:seed.revision,title:`S1 persistencia ${title}`}})));
assert.deepEqual(edits.map(r=>r.response.status).sort(),[200,409]);
const updated = await request(`/products/${product.slug}`);
assert.match(updated.data.title,/^S1 persistencia/);
const persisted = JSON.parse(await fs.readFile(stateFile,'utf8'));
assert.equal(persisted.products.find(p=>p.id===product.id).title,updated.data.title);
pass('Concurrent route mutations serialize; stale draft gets 409 and saved product reaches public API/disk');
await fs.writeFile(path.resolve('.soky-demo',folder,'restart-check.json'),JSON.stringify({cookie,productId:product.id,slug:product.slug,title:updated.data.title}));
const canceledBefore = await fs.readFile(stateFile,'utf8');
assert.equal((await request('/admin/demo/reset',{method:'POST',body:{expectedRevision:persisted.revision,confirm:'CANCEL'}})).response.status,422);
assert.equal(await fs.readFile(stateFile,'utf8'),canceledBefore);
const reset = await request('/admin/demo/reset',{method:'POST',body:{expectedRevision:persisted.revision,confirm:'RESTORE'}});
assert.equal(reset.response.status,200); assert.ok(reset.data.revision>persisted.revision);
assert.equal((await request('/auth/me')).response.status,200);
const afterReset = (await request('/admin/demo/workspace')).data;
for (const key of ['products','categories','sliders','settings','currentRate','rateHistory','analytics','orderIntents']) assert.deepEqual(afterReset[key],seed[key]);
pass('Canceled reset does nothing; confirmed reset restores all domains and preserves session');
await fs.writeFile(stateFile,'{broken-s1-http');
assert.equal((await request('/products')).response.status,503);
const corruptStatus = await request('/admin/demo/status');
assert.equal(corruptStatus.data.storageState,'corrupt');
const recoveryPage = await fetch(`${base}/admin-secret/demo`,{headers:{Cookie:cookie}});
assert.equal(recoveryPage.status,200);
assert.equal(await fs.readFile(stateFile,'utf8'),'{broken-s1-http');
const recovered = await request('/admin/demo/reset',{method:'POST',body:{expectedRevision:'RECOVER',confirm:'RESTORE'}});
assert.equal(recovered.response.status,200);
assert.ok(recovered.data.revision>reset.data.revision);
const backups = (await fs.readdir(path.dirname(stateFile))).filter(name=>name.startsWith('corrupt-'));
assert.ok((await Promise.all(backups.map(name=>fs.readFile(path.join(path.dirname(stateFile),name),'utf8')))).includes('{broken-s1-http'));
pass('Corrupt HTTP dataset stays intact; independent recovery page works and explicit reset saves backup');
const rate = await request('/admin/exchange-rates/manual',{method:'POST',body:{expectedRevision:recovered.data.revision,baseCurrency:'EUR',rate:'1000.000000',fetchedAt:new Date().toISOString()}});
assert.equal(rate.response.status,200);
const quote = await request('/cart/quote',{method:'POST',session:false,body:{items:[{productId:product.id,quantity:1}],fulfillmentType:'PICKUP'}});
assert.equal(quote.response.status,200);
const order = await request('/order-intents',{method:'POST',session:false,body:{items:[{productId:product.id,quantity:1}],fulfillmentType:'PICKUP',customerName:'Cliente de prueba',expectedRate:quote.data.rateSnapshot,expectedTotalVes:quote.data.totals.totalVes}});
assert.equal(order.response.status,201);
assert.equal(order.data.demoPreview,true); assert.equal(order.data.whatsappUrl,'');
pass('Server re-quotes demo intent and returns a preview without WhatsApp destination');
const oldCookie = cookie;
assert.equal((await request('/auth/logout',{method:'POST'})).response.status,200);
assert.equal((await request('/auth/me')).response.status,401);
cookie = 'soky_demo_session=arbitrary';
assert.equal((await request('/auth/refresh',{method:'POST'})).response.status,401);
pass('Logout revokes token and arbitrary session cannot refresh');
// Persist a check for a real Next restart after this suite.
await fs.writeFile(path.resolve('.soky-demo',folder,'restart-check.json'),JSON.stringify({cookie:oldCookie,productId:product.id,slug:product.slug,title:seed.products.find(p=>p.id===product.id).title}));
await fs.mkdir('qa/admin-demo/s1', {recursive:true});
await fs.writeFile('qa/admin-demo/s1/api-results.json',JSON.stringify({base,total:checks,passed:checks},null,2));
console.log(JSON.stringify({total:checks,passed:checks}));
