import assert from 'node:assert/strict';
import { mock } from 'node:test';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const folder = `qa-s1-${randomUUID()}`;
process.env.SOKY_DEMO_DATA_FOLDER = folder;
process.env.SOKY_DEMO_MODE = 'on';
const directory = path.resolve('.soky-demo', folder);
const stateFile = path.join(directory, 'state.json');
let failRename = false;
mock.module('node:fs/promises', { namedExports: { ...fs, rename: async (...args) => { if (failRename) throw Object.assign(new Error('simulated write failure'), { code: 'EACCES' }); return fs.rename(...args); } } });
const repo = await import('../src/mock/demo-repository.ts');
const { createDemoSeed } = await import('../src/mock/demo-seed.ts');
const { validateState } = await import('../src/mock/demo-validation.ts');
const { safeAdminReturn } = await import('../src/features/admin/return-path.ts');
const checks = [];
const pass = name => { checks.push(name); console.log(`PASS ${name}`); };
try {
  await assert.rejects(fs.stat(stateFile), { code: 'ENOENT' });
  pass('Importing modules does not create the dataset');
  const initial = await repo.readDemoState();
  validateState(initial);
  const { mapPublicSettingsToContact } = await import('../src/features/settings/mappers.ts');
  for (const phone of ['12345678', '123456789012345']) {
    assert.ok(mapPublicSettingsToContact({ ...initial.settings, whatsappPhone: phone, demoPreview: true }).whatsappUrl.startsWith('/demo/whatsapp?'));
  }
  assert.equal(mapPublicSettingsToContact({ ...initial.settings, whatsappPhone: '1234567', demoPreview: true }).whatsappUrl, undefined);
  const originalTitle = initial.products[0].title;
  const changed = await repo.mutateDemo(initial.revision, draft => { draft.products[0].title = 'Prueba persistente S1'; });
  assert.equal(initial.products[0].title, originalTitle);
  assert.equal(createDemoSeed().products[0].title, originalTitle);
  assert.equal(JSON.parse(await fs.readFile(stateFile, 'utf8')).products[0].title, 'Prueba persistente S1');
  pass('Immutable seed and persisted product mutation');
  await assert.rejects(repo.mutateDemo(changed.state.revision, draft => { draft.sliders[0].productId = 'missing-product'; }), error => error.code === 'DATA_CORRUPT');
  await assert.rejects(repo.mutateDemo(changed.state.revision, draft => { draft.products[0].priceCurrency = 'USD'; }));
  await assert.rejects(repo.mutateDemo(changed.state.revision, draft => { draft.analytics.summary.productViews = -1; }), error => error.code === 'DATA_CORRUPT');
  assert.equal((await repo.readDemoState()).revision, changed.state.revision);
  pass('Invalid references, mixed currency and malformed fixtures do not commit');
  const restart = execFileSync(process.execPath, ['--import', './tests/demo-loader.mjs', '--input-type=module', '-e', 'const {readDemoState}=await import("./src/mock/demo-repository.ts");console.log((await readDemoState()).products[0].title)'], { env: process.env, encoding: 'utf8', windowsHide: true });
  assert.equal(restart.trim(), 'Prueba persistente S1');
  pass('New Node process reloads persisted changes');
  const secondBundle = await import('../src/mock/demo-repository.ts?second-bundle');
  const edits = await Promise.allSettled([repo.mutateDemo(changed.state.revision, d => { d.products[0].title = 'Edición A'; }), secondBundle.mutateDemo(changed.state.revision, d => { d.products[0].title = 'Edición B'; })]);
  assert.equal(edits.filter(e => e.status === 'fulfilled').length, 1);
  assert.equal(edits.find(e => e.status === 'rejected').reason.status, 409);
  pass('Global queue shares independently loaded modules; stale revision returns 409');
  const beforeFailure = await fs.readFile(stateFile, 'utf8');
  failRename = true;
  await assert.rejects(repo.mutateDemo(JSON.parse(beforeFailure).revision, draft => { draft.products[0].title = 'No debe aplicarse'; }), error => error.code === 'STORAGE_ERROR');
  failRename = false;
  assert.equal(await fs.readFile(stateFile, 'utf8'), beforeFailure);
  assert.equal((await repo.readDemoState()).products[0].title, JSON.parse(beforeFailure).products[0].title);
  assert.equal((await fs.readdir(directory)).filter(name => name.endsWith('.tmp')).length, 0);
  pass('Failed atomic replacement changes neither disk nor subsequent reads');
  await fs.writeFile(stateFile, '{invalid json');
  await assert.rejects(repo.readDemoState(), error => error.code === 'DATA_CORRUPT');
  await assert.rejects(repo.resetDemo(1), error => error.code === 'DATA_CORRUPT');
  assert.equal(await fs.readFile(stateFile, 'utf8'), '{invalid json');
  const recovered = await repo.resetDemo('RECOVER');
  const backups = (await fs.readdir(directory)).filter(name => name.startsWith('corrupt-'));
  assert.equal(await fs.readFile(path.join(directory, backups[0]), 'utf8'), '{invalid json');
  assert.ok(recovered.revision > JSON.parse(beforeFailure).revision);
  pass('Corrupt dataset preserved until explicit recovery, with backup and increasing revision');
  const unknown = { ...recovered, schemaVersion: 999 };
  await fs.writeFile(stateFile, JSON.stringify(unknown));
  await assert.rejects(repo.readDemoState(), error => error.code === 'DATA_CORRUPT');
  assert.equal(JSON.parse(await fs.readFile(stateFile, 'utf8')).schemaVersion, 999);
  const restored = await repo.resetDemo('RECOVER');
  const reset = await repo.resetDemo(restored.revision);
  assert.equal(reset.revision, restored.revision + 1);
  for (const key of ['products','categories','settings','sliders','rateHistory','analytics','orderIntents','currentRate']) assert.deepEqual(reset[key], createDemoSeed()[key]);
  pass('Unknown schema preserved; confirmed reset restores all areas without resetting revision');
  const auth = await import('../src/mock/demo-auth.ts');
  const token = auth.newSession();
  assert.ok(auth.validSession(token));
  assert.equal(auth.validSession('any-cookie'), false);
  const now = Date.now;
  Date.now = () => now() + 8 * 3600000 + 1;
  try { assert.equal(auth.validSession(token), false); } finally { Date.now = now; }
  const secondToken = auth.newSession();
  auth.logout(new Request('http://localhost/test', { headers: { Cookie: `${auth.SESSION_COOKIE}=${secondToken}` } }));
  assert.equal(auth.validSession(secondToken), false);
  pass('Opaque session rejects arbitrary values, expires after 8h, and revokes on logout');
  for (const input of ['https://evil.test', '//evil.test', '/admin-secret/../../evil', '/admin-secret/%2f%2fevil.test', '/admin-secret/\\evil.test', '/admin-secret/login']) assert.equal(safeAdminReturn(input, 'admin-secret'), '/admin-secret');
  assert.equal(safeAdminReturn('/admin-secret/products?draft=1', 'admin-secret'), '/admin-secret/products?draft=1');
  pass('Login return accepts internal admin destinations and rejects external/encoded escapes');
  const offFolder = `${folder}-off`;
  execFileSync(process.execPath, ['--import','./tests/demo-loader.mjs','--input-type=module','-e','const {readDemoState}=await import("./src/mock/demo-repository.ts"); const {mockProducts,mockSettings}=await import("./src/mock/db.ts"); const s=await readDemoState(); if(JSON.stringify(s.products)!==JSON.stringify(mockProducts)||JSON.stringify(s.settings)!==JSON.stringify(mockSettings))process.exit(1);'], { env: { ...process.env, SOKY_DEMO_MODE: 'off', SOKY_DEMO_DATA_FOLDER: offFolder }, windowsHide: true });
  await assert.rejects(fs.stat(path.resolve('.soky-demo', offFolder, 'state.json')), { code: 'ENOENT' });
  pass('Demo disabled reads original seeds without creating a dataset');
  await fs.mkdir('qa/admin-demo/s1', { recursive: true });
  await fs.writeFile('qa/admin-demo/s1/repository-results.json', JSON.stringify({ checks, total: checks.length, passed: checks.length }, null, 2));
  console.log(JSON.stringify({ total: checks.length, passed: checks.length }));
} finally {
  // Only the unique test directory created above is removed.
  if (directory.startsWith(path.resolve('.soky-demo') + path.sep) && path.basename(directory) === folder) await fs.rm(directory, { recursive: true, force: true });
}
